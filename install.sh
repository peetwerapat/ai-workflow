install_shell() {
  head2 "Shell wrapper (Codex + Antigravity auto-sync)"
  if [ -n "${AI_AGENT_NO_SHELL:-}" ]; then
    info "ข้าม — AI_AGENT_NO_SHELL ถูกตั้งไว้"
    return 0
  fi

  local rc
  rc="$(detect_rc)"
  if [ -z "$rc" ]; then
    warn "ไม่รู้จัก shell '${SHELL##*/}' — ข้าม (เพิ่ม wrapper เองได้ ดู README)"
    return 0
  fi

  strip_shell_block "$rc"
  {
    printf '\n%s\n' "$MARKER"
    printf '%s\n' "# sync skill ก่อนเปิดทุกครั้ง (Claude ใช้ symlink ไม่ต้อง sync)"
    printf '%s\n' "#   codex / agy - command ถูก generate เป็น SKILL.md ไม่ใช่ symlink"
    printf '%s\n' "codex() {"
    printf '%s\n' "  [ -x \"$ROOT/install.sh\" ] && AI_AGENT_NO_SHELL=1 \"$ROOT/install.sh\" codex >/dev/null 2>&1"
    printf '%s\n' "  command codex \"\$@\""
    printf '%s\n' "}"
    printf '%s\n' "agy() {"
    printf '%s\n' "  [ -x \"$ROOT/install.sh\" ] && AI_AGENT_NO_SHELL=1 \"$ROOT/install.sh\" antigravity >/dev/null 2>&1"
    printf '%s\n' "  command agy \"\$@\""
    printf '%s\n' "}"
    printf '%s\n' "$MARKER_END"
  } >> "$rc"

  ok "$rc — ตั้ง codex() + agy() wrapper ชี้ไป $ROOT"
  info "เปิด terminal ใหม่ หรือ: source $rc"
}

uninstall() {
  head2 "Uninstall"
  local removed=0 path
  for path in "$AI_HOME" \
              "$CLAUDE_HOME/CLAUDE.md" "$CODEX_HOME/AGENTS.md" \
              "$CLAUDE_HOME"/commands/*.md "$CLAUDE_HOME"/agents/*.md \
              "$ZCODE_HOME/AGENTS.md" "$ZCODE_HOME"/commands/*.md; do
    is_ours_link "$path" || continue
    rm -f "$path"; info "ลบ $path"; removed=$((removed + 1))
  done
  for path in "$AGY_HOME"/skills/*/SKILL.md "$CODEX_HOME"/skills/*/SKILL.md; do
    [ -f "$path" ] || continue
    if grep -q 'generated by ai-agent' "$path"; then
      rm -rf "$(dirname "$path")"; info "ลบ $(dirname "$path")"; removed=$((removed + 1))
    fi
  done
  for path in "$CLAUDE_HOME"/agents/*.md "$CODEX_HOME"/agents/*.toml \
              "$AGY_HOME"/agents/*.md "$ZCODE_HOME"/agents/*.md; do
    [ -f "$path" ] && [ ! -L "$path" ] || continue
    if grep -q 'generated by ai-agent' "$path"; then
      rm -f "$path"; info "ลบ $path"; removed=$((removed + 1))
    fi
  done
  local backup
  for backup in "$CODEX_HOME/skills-disabled-old-template" "$AGY_HOME/skills-disabled-old"; do
    [ -d "$backup" ] && warn "skill เดิมอยู่ที่ $backup/ — กู้เองได้ด้วย mv"
  done
  local rc
  rc="$(detect_rc)"
  if [ -n "$rc" ] && [ -f "$rc" ] && grep -qF "$MARKER" "$rc"; then
    strip_shell_block "$rc"
    info "ลบ codex()/agy() wrapper จาก $rc"
    removed=$((removed + 1))
  fi
  # ที่เก็บถาวร — ลบเป็นอย่างสุดท้าย (script ตัวเองอาจอยู่ในนี้ แต่ fd เปิดค้างไว้แล้ว)
  if [ -d "$AI_AGENT_HOME" ] && [ -f "$AI_AGENT_HOME/ai/AI.md" ]; then
    rm -rf "$AI_AGENT_HOME"
    info "ลบ $AI_AGENT_HOME"
    removed=$((removed + 1))
  fi
  ok "ลบไปทั้งหมด $removed รายการ (ไฟล์ .bak-* ยังอยู่ ถ้าต้องการกู้คืน)"
}

status() {
  head2 "Status"
  local path dir rc url commit
  if [ -f "$AI_AGENT_HOME/ai/AI.md" ]; then
    ok "ที่เก็บถาวร: $AI_AGENT_HOME (ลบ clone ต้นทางได้)"
    if [ -f "$SOURCE_FILE" ]; then
      url="$(sed -n 's/^AI_AGENT_SOURCE_URL=//p' "$SOURCE_FILE")"
      commit="$(sed -n 's/^AI_AGENT_SOURCE_COMMIT=//p' "$SOURCE_FILE" | cut -c1-7)"
      info "ต้นทาง: ${url:-ไม่ทราบ} ${commit:+@ $commit}"
    fi
  else
    warn "ยังไม่มี $AI_AGENT_HOME — ยังไม่ได้ติดตั้ง หรือ link ตรงเข้า repo อยู่"
  fi
  for path in "$AI_HOME" "$CLAUDE_HOME/CLAUDE.md" "$CODEX_HOME/AGENTS.md" "$ZCODE_HOME/AGENTS.md"; do
    if [ -L "$path" ]; then ok "$path → $(readlink "$path")"; else warn "$path ยังไม่ได้ติดตั้ง"; fi
  done
  for dir in "$CLAUDE_HOME/commands" "$CLAUDE_HOME/agents" "$CODEX_HOME/skills" "$CODEX_HOME/agents" "$AGY_HOME/skills" "$AGY_HOME/agents" \
             "$ZCODE_HOME/commands" "$ZCODE_HOME/agents"; do
    [ -d "$dir" ] && info "$dir — $(count_dir "$dir") รายการ"
  done
  rc="$(detect_rc)"
  if [ -n "$rc" ] && [ -f "$rc" ] && grep -qF "$MARKER" "$rc"; then
    ok "$rc — มี codex()/agy() wrapper"
  else
    warn "ยังไม่มี codex()/agy() wrapper (รัน: $0 shell)"
  fi
}

# ---------- เมนูเลือก assistant ----------

SEL_CLAUDE=1 SEL_CODEX=1 SEL_AGY=1 SEL_ZCODE=1 SEL_SHELL=1

# ค่า default: ติ๊กเฉพาะตัวที่มี binary จริงในเครื่อง
detect_defaults() {
  command -v claude >/dev/null 2>&1 && SEL_CLAUDE=1 || SEL_CLAUDE=0
  command -v codex  >/dev/null 2>&1 && SEL_CODEX=1  || SEL_CODEX=0
  command -v agy    >/dev/null 2>&1 && SEL_AGY=1    || SEL_AGY=0
  detect_zcode
  # shell wrapper จำเป็นเฉพาะตัวที่ต้อง generate ไฟล์
  if [ "$SEL_CODEX" = 1 ] || [ "$SEL_AGY" = 1 ]; then SEL_SHELL=1; else SEL_SHELL=0; fi
}

# ZCode เป็น desktop app ไม่มี binary ใน PATH — ดูจาก ~/.zcode ที่ app สร้างไว้แทน
detect_zcode() {
  [ -d "$ZCODE_HOME" ] && SEL_ZCODE=1 || SEL_ZCODE=0
}

load_prefs() {
  [ -f "$PREFS" ] || return 1
  # prefs รุ่นก่อนมี ZCode ไม่มี SEL_ZCODE — auto-detect แทน ไม่ติ๊กให้มั่วๆ
  detect_zcode
  # shellcheck disable=SC1090
  . "$PREFS"
  return 0
}

save_prefs() {
  cat > "$PREFS" <<PREFSEOF
# ตัวเลือกล่าสุดของ ./install.sh — ลบไฟล์นี้เพื่อกลับไปใช้ค่า auto-detect
SEL_CLAUDE=$SEL_CLAUDE
SEL_CODEX=$SEL_CODEX
SEL_AGY=$SEL_AGY
SEL_ZCODE=$SEL_ZCODE
SEL_SHELL=$SEL_SHELL
PREFSEOF
  [ "$DEV_MODE" = 1 ] && printf 'AI_AGENT_DEV=1\n' >> "$PREFS"
  return 0
}

LABELS=("Claude Code" "Codex CLI" "Antigravity CLI" "ZCode" "Shell wrapper")
SEL=(1 1 1 1 1)
CURSOR=0
MENU_LINES=0
STTY_SAVED=""

hint_for() {
  case "$1" in
    0) binary_hint claude ;;
    1) binary_hint codex ;;
    2) binary_hint agy ;;
    3) if [ -d "$ZCODE_HOME" ]; then printf 'พบ %s' "${ZCODE_HOME/#$HOME/~}"; else printf 'ไม่พบ ~/.zcode ในเครื่อง'; fi ;;
    4) printf 'auto-sync ตอนเปิด codex/agy' ;;
  esac
}

binary_hint() {
  if command -v "$1" >/dev/null 2>&1; then
    printf 'พบ %s' "$1"
  else
    printf 'ไม่พบ %s ในเครื่อง' "$1"
  fi
}

# ย้ายค่าระหว่างตัวแปร SEL_* กับ array ที่เมนูใช้
sel_to_array() { SEL=("$SEL_CLAUDE" "$SEL_CODEX" "$SEL_AGY" "$SEL_ZCODE" "$SEL_SHELL"); }
array_to_sel() {
  SEL_CLAUDE="${SEL[0]}"; SEL_CODEX="${SEL[1]}"
  SEL_AGY="${SEL[2]}";    SEL_ZCODE="${SEL[3]}"
  SEL_SHELL="${SEL[4]}"
}

restore_term() {
  printf '\033[?25h'                                  # โชว์ cursor กลับ
  [ -n "$STTY_SAVED" ] && stty "$STTY_SAVED" 2>/dev/null || true
}

draw_menu() {
  printf '\n\033[1m  เลือก assistant ที่จะติดตั้ง\033[0m\n\n'
  local i pointer box label_style
  for i in "${!LABELS[@]}"; do
    if [ "$i" = "$CURSOR" ]; then pointer=$'\033[36m❯\033[0m'; label_style=$'\033[1m'
    else                          pointer=' ';                   label_style=''
    fi
    if [ "${SEL[$i]}" = 1 ]; then box=$'\033[32m◉\033[0m'
    else                          box='◯'
    fi
    printf '  %b %b %b%-18s\033[0m \033[2m%s\033[0m\n' \
      "$pointer" "$box" "$label_style" "${LABELS[$i]}" "$(hint_for "$i")"
  done
  printf '\n  \033[2m↑/↓ เลื่อน · space ติ๊ก · a ทั้งหมด · n ล้าง · enter ยืนยัน · q ออก\033[0m\n'
  MENU_LINES=$((3 + ${#LABELS[@]} + 2))
}

redraw_menu() {
  printf '\033[%dA\033[J' "$MENU_LINES"
  draw_menu
}

# อ่าน 1 keystroke แล้วแปลเป็นชื่อปุ่ม (ลูกศรมาเป็น escape sequence 3 ไบต์: ESC [ A)
#
# bash 3.2 (ตัว default ของ macOS) ไม่รองรับ `read -t` แบบทศนิยม — จะคุม timeout
# ของ escape sequence ด้วย stty `min 0 time 1` (รอไม่เกิน 0.1 วิ แล้วคืนเท่าที่มี)
# เพื่อให้กด Esc เปล่าๆ ไม่ค้างรอปุ่มถัดไป
read_key() {
  local key rest
  IFS= read -rsn1 key 2>/dev/null || return 1
  case "$key" in
    $'\e')
      rest=""
      if [ -n "$STTY_SAVED" ]; then
        stty min 0 time 1 2>/dev/null || true
        IFS= read -rsn2 rest 2>/dev/null || true
        stty min 1 time 0 2>/dev/null || true
      else
        IFS= read -rsn2 -t 1 rest 2>/dev/null || true
      fi
      case "$rest" in
        '[A') printf 'up' ;;
        '[B') printf 'down' ;;
        *)    printf 'esc' ;;
      esac ;;
    '')  printf 'enter' ;;
    ' ') printf 'space' ;;
    *)   printf '%s' "$key" ;;
  esac
}

toggle_at() {
  local i="$1"
  [ "${SEL[$i]}" = 1 ] && SEL[$i]=0 || SEL[$i]=1
}

choose_menu() {
  sel_to_array

  STTY_SAVED="$(stty -g 2>/dev/null || true)"
  trap restore_term EXIT INT TERM
  # อ่านทีละปุ่ม ไม่ต้องรอ Enter และไม่ echo ตัวอักษรที่กด
  [ -n "$STTY_SAVED" ] && stty -echo -icanon min 1 time 0 2>/dev/null || true
  printf '\033[?25l'                                   # ซ่อน cursor ระหว่างเลือก

  local key i result=0
  draw_menu
  while :; do
    key="$(read_key)" || { result=1; break; }
    case "$key" in
      up|k)    CURSOR=$(( (CURSOR - 1 + ${#LABELS[@]}) % ${#LABELS[@]} )) ;;
      down|j)  CURSOR=$(( (CURSOR + 1) % ${#LABELS[@]} )) ;;
      space)   toggle_at "$CURSOR" ;;
      a|A)     for i in "${!LABELS[@]}"; do SEL[$i]=1; done ;;
      n|N)     for i in "${!LABELS[@]}"; do SEL[$i]=0; done ;;
      [1-5])   CURSOR=$((key - 1)); toggle_at "$CURSOR" ;;
      enter)   break ;;
      q|Q|esc) result=1; break ;;
    esac
    redraw_menu
  done

  restore_term
  trap - EXIT INT TERM

  if [ "$result" = 1 ]; then
    info "ยกเลิก"
    return 1
  fi

  array_to_sel
  if [ "$SEL_CLAUDE$SEL_CODEX$SEL_AGY$SEL_ZCODE$SEL_SHELL" = "00000" ]; then
    warn "ไม่ได้เลือกอะไรเลย — ไม่มีอะไรให้ทำ"
    return 1
  fi
  save_prefs
  return 0
}

run_selected() {
  # install_shared ต้องรันเสมอถ้ามีการติดตั้ง assistant ตัวใดตัวหนึ่ง
  if [ "$SEL_CLAUDE" = 1 ] || [ "$SEL_CODEX" = 1 ] || [ "$SEL_AGY" = 1 ] || [ "$SEL_ZCODE" = 1 ]; then
    install_shared
  fi
  [ "$SEL_CLAUDE" = 1 ] && install_claude
  [ "$SEL_CODEX"  = 1 ] && install_codex
  [ "$SEL_AGY"    = 1 ] && install_antigravity
  [ "$SEL_ZCODE"  = 1 ] && install_zcode
  [ "$SEL_SHELL"  = 1 ] && install_shell
  return 0
}

summary() {
  head2 "เสร็จแล้ว"
  [ "$SEL_CLAUDE" = 1 ] && info "Claude      → /status, /ai-init"
  [ "$SEL_CODEX"  = 1 ] && info "Codex       → \$status, \$ai-init"
  [ "$SEL_AGY"    = 1 ] && info "Antigravity → เรียกชื่อ skill ได้เลย (agy)"
  [ "$SEL_ZCODE"  = 1 ] && info "ZCode       → /status, /ai-init"
  [ "$SEL_SHELL"  = 1 ] && info "เปิด terminal ใหม่ หรือ source shell rc ก่อนใช้ wrapper"
  if [ -n "${AI_AGENT_FROM:-}" ]; then
    info ""
    ok "ทุกอย่างอยู่ที่ $AI_AGENT_HOME แล้ว — ลบ $AI_AGENT_FROM ทิ้งได้เลย"
    info "อัปเดตรอบหน้า: $AI_AGENT_HOME/install.sh --update"
  fi
  return 0
}

main() {
  local arg cmd="" do_update=0
  for arg in "$@"; do
    case "$arg" in
      --dev)    DEV_MODE=1 ;;
      --update) do_update=1 ;;
      *)        cmd="$arg" ;;
    esac
  done

  [ "${AI_AGENT_DEV:-0}" = 1 ] && DEV_MODE=1
  dev_mode_remembered && DEV_MODE=1

  if [ "$do_update" = 1 ]; then
    update
    return
  fi

  [ -d "$SRC" ] || { echo "ไม่พบ $SRC" >&2; exit 1; }

  # --status / --uninstall ไม่ต้อง copy อะไร ทำงานจากที่ไหนก็ได้
  case "$cmd" in
    --uninstall) uninstall; return ;;
    --status)    status; return ;;
    ""|all|claude|codex|antigravity|agy|zcode|shell) ;;
    *)
      echo "ใช้: $0 [all|claude|codex|antigravity|zcode|shell] | --status | --update | --uninstall" >&2
      exit 1
      ;;
  esac

  # default: ย้ายตัวเองไปที่ถาวรก่อน แล้ว re-exec จากที่นั่น
  if [ "$DEV_MODE" = 1 ]; then
    remember_dev_mode
  elif [ -z "${AI_AGENT_SELF_INSTALLED:-}" ] && ! same_path "$ROOT" "$AI_AGENT_HOME"; then
    self_install "$@"
  fi

  case "$cmd" in
    claude)      SEL_CLAUDE=1 SEL_CODEX=0 SEL_AGY=0 SEL_ZCODE=0 SEL_SHELL=0 ;;
    codex)       SEL_CLAUDE=0 SEL_CODEX=1 SEL_AGY=0 SEL_ZCODE=0 SEL_SHELL=0 ;;
    antigravity|agy) SEL_CLAUDE=0 SEL_CODEX=0 SEL_AGY=1 SEL_ZCODE=0 SEL_SHELL=0 ;;
    zcode)       SEL_CLAUDE=0 SEL_CODEX=0 SEL_AGY=0 SEL_ZCODE=1 SEL_SHELL=0 ;;
    shell)       SEL_CLAUDE=0 SEL_CODEX=0 SEL_AGY=0 SEL_ZCODE=0 SEL_SHELL=1 ;;
    all)         SEL_CLAUDE=1 SEL_CODEX=1 SEL_AGY=1 SEL_ZCODE=1 SEL_SHELL=1 ;;
    "")
      # ไม่ระบุ arg: ใช้ค่าที่เคยเลือกไว้ ถ้าไม่มีก็ auto-detect จาก binary ที่ติดตั้งจริง
      load_prefs || detect_defaults
      if [ -t 0 ] && [ -z "${AI_AGENT_YES:-}" ]; then
        choose_menu || return 0
      else
        info "โหมด non-interactive — ใช้ค่าที่บันทึกไว้/auto-detect"
      fi
      ;;
  esac

  run_selected
  summary
}

main "$@"
