#!/usr/bin/env bash
#
# ติดตั้งชุด AI กลาง (ai/) ให้ Claude Code, Codex CLI, Antigravity CLI และ ZCode ใช้ร่วมกันทุก project
#
#   ./install.sh              เลือกจากเมนูว่าจะติดตั้งตัวไหน (จำค่าที่เลือกไว้รอบหน้า)
#   ./install.sh all          ติดตั้งทุกตัว ไม่ถามเมนู
#   ./install.sh claude       ติดตั้งเฉพาะที่ระบุ (claude | codex | antigravity | zcode | shell)
#   ./install.sh --status     ดูว่าติดตั้งอะไรไว้บ้าง
#   ./install.sh --update     ดึงเวอร์ชันใหม่จากต้นทางแล้วติดตั้งทับ
#   ./install.sh --uninstall  ถอนเฉพาะสิ่งที่ script นี้สร้าง (รวม ~/.ai-agent)
#
# script จะ copy ตัวเอง + ai/ ไปไว้ที่ ~/.ai-agent ก่อน แล้วค่อย link จากตรงนั้น
# — folder ที่ clone มาจึงลบทิ้งได้ทันทีหลังติดตั้งเสร็จ
#
# env: AI_AGENT_NO_SHELL=1  ข้ามการแก้ shell rc
#      AI_AGENT_HOME=<dir>  เปลี่ยนที่เก็บถาวร (default ~/.ai-agent)
#
set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SRC="$ROOT/ai"
STAMP="$(date +%Y%m%d-%H%M%S)"

# ที่เก็บถาวรของชุด AI — copy มาไว้ที่นี่เพื่อให้ลบ clone ทิ้งได้
AI_AGENT_HOME="${AI_AGENT_HOME:-$HOME/.ai-agent}"
SOURCE_FILE="$AI_AGENT_HOME/.source"
DEV_MODE=0

CLAUDE_HOME="${CLAUDE_HOME:-$HOME/.claude}"
CODEX_HOME="${CODEX_HOME:-$HOME/.codex}"
# Antigravity CLI (agy) — customization root ระดับ global
AGY_HOME="${AGY_HOME:-$HOME/.gemini/config}"
# ZCode (Z.ai desktop app, agent glm) — global AGENTS.md / commands / agents
ZCODE_HOME="${ZCODE_HOME:-$HOME/.zcode}"
AI_HOME="${AI_HOME:-$HOME/.ai}"

PREFS="$ROOT/.install-prefs"

MARKER="# >>> ai-agent sync >>>"
MARKER_END="# <<< ai-agent sync <<<"

info()  { printf '  %s\n' "$*"; }
head2() { printf '\n\033[1m%s\033[0m\n' "$*"; }
warn()  { printf '  \033[33m!\033[0m %s\n' "$*"; }
ok()    { printf '  \033[32m✓\033[0m %s\n' "$*"; }
count() { ls -1 "$@" 2>/dev/null | wc -l | tr -d ' '; }
count_dir() { ls -1 "$1" 2>/dev/null | wc -l | tr -d ' '; }

# symlink ที่ script นี้เป็นคนสร้าง — รวม path เก่าตอนที่ยัง link ตรงเข้า clone
is_ours_link() {
  [ -L "$1" ] || return 1
  case "$(readlink "$1")" in
    "$SRC"|"$SRC"/*|"$AI_HOME"|"$AI_HOME"/*) return 0 ;;
    "$AI_AGENT_HOME"/ai|"$AI_AGENT_HOME"/ai/*) return 0 ;;
    */ai/AI.md|*/ai/commands/*.md|*/ai/agents/*.md) return 0 ;;   # ติดตั้งไว้จาก clone ที่อื่น
  esac
  return 1
}

# ย้ายไฟล์จริง (ที่ไม่ใช่ symlink ของเรา) ไปเป็น .bak ก่อนเขียนทับ
backup_if_real() {
  local target="$1"
  [ -e "$target" ] || [ -L "$target" ] || return 0
  is_ours_link "$target" && return 0
  # symlink เสียค้าง (clone เดิมถูกลบไปแล้ว) — ลบทิ้งได้เลย ไม่ต้องสำรอง
  if [ -L "$target" ] && [ ! -e "$target" ]; then
    rm -f "$target"
    return 0
  fi
  mv "$target" "$target.bak-$STAMP"
  warn "สำรองของเดิม → $(basename "$target").bak-$STAMP"
}

same_path() {
  local a b
  a="$(cd "$1" 2>/dev/null && pwd -P)" || a="$1"
  b="$(cd "$2" 2>/dev/null && pwd -P)" || b="$2"
  [ "$a" = "$b" ]
}

link() {
  local src="$1" dst="$2"
  backup_if_real "$dst"
  mkdir -p "$(dirname "$dst")"
  ln -sfn "$src" "$dst"
}

# copy ไฟล์จริง — ใช้กับ runtime ที่ไม่ follow symlink (Codex)
# แปลง command markdown → SKILL.md (ใช้ได้ทั้ง Codex และ Antigravity)
md_to_skill() {
  local src="$1" dst="$2" name="$3"
  mkdir -p "$(dirname "$dst")"
  python3 - "$src" "$dst" "$name" <<'SKILLPY'
import re, sys, pathlib

src, dst, name = pathlib.Path(sys.argv[1]), pathlib.Path(sys.argv[2]), sys.argv[3]
raw = src.read_text(encoding="utf-8")

description = ""
match = re.match(r"^---\r?\n(.*?)\r?\n---\r?\n?", raw, re.S)
if match:
    for line in match.group(1).splitlines():
        key, _, value = line.partition(":")
        if key.strip() == "description":
            description = value.strip().strip("'\"")
    body = raw[match.end():]
else:
    body = raw

# Codex ส่งข้อความที่ user พิมพ์ต่อท้าย $<name> เข้ามาเป็น input
body = body.replace("$ARGUMENTS", f"ข้อความที่ user พิมพ์ต่อท้าย `${name}`")

def quote(text):
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'

dst.write_text(
    "---\n"
    f"name: {name}\n"
    f"description: {quote(description)}\n"
    "---\n\n"
    f"<!-- generated by ai-agent install.sh from ai/commands/{src.name} - DO NOT EDIT -->\n\n"
    "> อ่าน `~/.ai/AI.md` (rule กลาง) ก่อนเริ่ม ถ้ายังไม่ได้อ่านใน session นี้\n\n"
    + body.strip() + "\n",
    encoding="utf-8",
)
SKILLPY
}

# Render provider-specific agent files from one prompt and models.json.
render_agent() {
  local src="$1" provider="$2" dst="$3" generated
  generated="$(mktemp)"
  if ! python3 - "$src" "$provider" "$generated" <<'AGENTPY'
import json
import pathlib
import re
import sys

source, provider, destination = pathlib.Path(sys.argv[1]), sys.argv[2], pathlib.Path(sys.argv[3])
if provider not in {"claude", "codex", "antigravity", "zcode"}:
    raise ValueError(f"Unsupported provider: {provider}")

raw = source.read_text(encoding="utf-8")
match = re.match(r"\A---\n(.*?)\n---\n", raw, re.S)
if not match:
    raise ValueError(f"Missing frontmatter: {source}")
metadata = {}
for line in match.group(1).splitlines():
    key, separator, value = line.partition(":")
    if separator:
        metadata[key.strip()] = value.strip()
name, description = metadata.get("name"), metadata.get("description")
if not name or not description or name != source.stem:
    raise ValueError(f"Invalid name or description: {source}")

settings = json.loads((source.parent / "models.json").read_text(encoding="utf-8"))[name][provider]
model, effort = settings.get("model"), settings.get("effort")
if not model or (provider in {"antigravity", "zcode"} and effort and model == "inherit"):
    raise ValueError(f"Invalid model/effort for {name}/{provider}")
if provider == "antigravity" and effort:
    raise ValueError("Antigravity agent frontmatter has no effort field")

marker = f"<!-- generated by ai-agent install.sh from ai/agents/{source.name} - DO NOT EDIT -->"
body = raw[match.end():].lstrip("\n")
if provider == "codex":
    fields = [
        f"name = {json.dumps(name)}",
        f"description = {json.dumps(description, ensure_ascii=False)}",
        f"model = {json.dumps(model)}",
    ]
    if effort:
        fields.append(f"model_reasoning_effort = {json.dumps(effort)}")
    fields.extend([
        'sandbox_mode = "read-only"',
        f"developer_instructions = {json.dumps(marker + chr(10) + chr(10) + body, ensure_ascii=False)}",
    ])
    output = "\n".join(fields) + "\n"
else:
    fields = ["---", f"name: {name}", f"description: {json.dumps(description, ensure_ascii=False)}", f"model: {model}"]
    if provider == "claude" and effort:
        fields.append(f"effort: {effort}")
    if provider == "zcode" and effort:
        fields.append(f"thoughtLevel: {effort}")
    if provider == "antigravity":
        fields.extend(["mainAgent: false", "subagent: true"])
    output = "\n".join(fields + ["---", "", marker, "", body]).rstrip() + "\n"

destination.write_text(output, encoding="utf-8")
AGENTPY
  then
    rm -f "$generated"
    return 1
  fi
  # Remove old symlinks before writing so the generator cannot overwrite its source.
  if is_ours_link "$dst"; then
    rm -f "$dst"
  elif [ -f "$dst" ] && [ ! -L "$dst" ] && grep -q 'generated by ai-agent' "$dst"; then
    rm -f "$dst"
  else
    backup_if_real "$dst"
  fi
  mkdir -p "$(dirname "$dst")"
  mv "$generated" "$dst"
}

link_dir_contents() {
  local src_dir="$1" dst_dir="$2" ext="$3"
  local file
  for file in "$src_dir"/*"$ext"; do
    [ -e "$file" ] || continue
    link "$file" "$dst_dir/$(basename "$file")"
  done
}

detect_rc() {
  case "${SHELL##*/}" in
    zsh)  printf '%s\n' "$HOME/.zshrc" ;;
    bash) if [ -f "$HOME/.bash_profile" ]; then printf '%s\n' "$HOME/.bash_profile"; else printf '%s\n' "$HOME/.bashrc"; fi ;;
    *)    printf '%s\n' "" ;;
  esac
}

# ลบ block เดิมของเราออกจาก shell rc (กัน path เก่าค้างเวลาย้ายโฟลเดอร์)
strip_shell_block() {
  local rc="$1" tmp
  [ -f "$rc" ] || return 0
  grep -q 'ai-agent.*sync >>>' "$rc" || return 0
  tmp="$(mktemp)"
  # match ทุก marker ของ ai-agent ไม่ผูกกับชื่อรุ่นใดรุ่นหนึ่ง — กัน block ค้างตอนเปลี่ยนชื่อ
  awk '
    /^# >>> ai-agent.* sync >>>$/ { skip = 1 }
    !skip                         { print }
    /^# <<< ai-agent.* sync <<<$/ { skip = 0 }
  ' "$rc" > "$tmp"
  mv "$tmp" "$rc"
}

# ---------- self-install (copy ไปที่ถาวร แล้วลบ clone ได้) ----------
# maintainer เท่านั้น: --dev / AI_AGENT_DEV=1 ข้ามการ copy แล้ว link ตรงเข้า repo
# ไม่ประกาศใน README/usage — ต้นทางแก้ ai/ ที่เดียว เครื่องอื่นเป็นผู้ใช้อย่างเดียว

dev_mode_remembered() {
  [ -f "$ROOT/.install-prefs" ] && grep -q '^AI_AGENT_DEV=1' "$ROOT/.install-prefs"
}

remember_dev_mode() {
  local tmp
  info "maintainer mode — link ตรงเข้า $ROOT (ห้ามลบ repo นี้)"
  if [ -f "$PREFS" ]; then
    grep -q '^AI_AGENT_DEV=1' "$PREFS" && return 0
    tmp="$(mktemp)"
    grep -v '^AI_AGENT_DEV=' "$PREFS" > "$tmp" || true
    printf 'AI_AGENT_DEV=1\n' >> "$tmp"
    mv "$tmp" "$PREFS"
  else
    printf '%s\n%s\n' "# ตัวเลือกล่าสุดของ ./install.sh" "AI_AGENT_DEV=1" > "$PREFS"
  fi
  info "จำไว้ใน .install-prefs แล้ว — รอบหน้าไม่ต้องใส่ flag ซ้ำ"
}

# จด git remote + commit ไว้ ให้ --update รู้ว่าจะไปดึงจากไหนตอนที่ clone ถูกลบไปแล้ว
record_source() {
  local dir="$1" url="" commit=""
  if command -v git >/dev/null 2>&1 && git -C "$dir" rev-parse --git-dir >/dev/null 2>&1; then
    url="$(git -C "$dir" remote get-url origin 2>/dev/null || true)"
    commit="$(git -C "$dir" rev-parse HEAD 2>/dev/null || true)"
  fi
  cat > "$SOURCE_FILE" <<SRCEOF
# ที่มาของชุดนี้ — ใช้โดย ./install.sh --update (generated)
AI_AGENT_SOURCE_URL=$url
AI_AGENT_SOURCE_COMMIT=$commit
AI_AGENT_INSTALLED_AT=$STAMP
SRCEOF
}

# copy ai/ + install.sh ไป $AI_AGENT_HOME แล้ว re-exec จากที่นั่น
# ทุก symlink หลังจากนี้จะชี้ไป $AI_AGENT_HOME ไม่ใช่ clone → ลบ clone ได้ทันที
self_install() {
  head2 "Self-install"
  mkdir -p "$AI_AGENT_HOME"
  rm -rf "$AI_AGENT_HOME/ai"
  cp -R "$SRC" "$AI_AGENT_HOME/ai"
  cp "$ROOT/install.sh" "$AI_AGENT_HOME/install.sh"
  chmod +x "$AI_AGENT_HOME/install.sh"
  [ -f "$ROOT/README.md" ] && cp "$ROOT/README.md" "$AI_AGENT_HOME/README.md"
  record_source "$ROOT"
  ok "copy ชุด AI → $AI_AGENT_HOME"
  export AI_AGENT_SELF_INSTALLED=1
  export AI_AGENT_FROM="$ROOT"
  exec "$AI_AGENT_HOME/install.sh" "$@"
}

update() {
  head2 "Update"
  if [ ! -f "$SOURCE_FILE" ]; then
    warn "ไม่พบ $SOURCE_FILE"
    info "ยังไม่เคยติดตั้งจาก clone — clone repo แล้วรัน ./install.sh ก่อน"
    exit 1
  fi
  # shellcheck disable=SC1090
  . "$SOURCE_FILE"
  if [ -z "${AI_AGENT_SOURCE_URL:-}" ]; then
    warn "ไม่รู้ต้นทาง (repo ที่ติดตั้งมาไม่มี git remote) — clone เองแล้วรัน ./install.sh"
    exit 1
  fi
  command -v git >/dev/null 2>&1 || { warn "ต้องมี git ถึงจะ --update ได้"; exit 1; }

  local tmp
  tmp="$(mktemp -d)"
  trap 'rm -rf "$tmp"' EXIT
  info "ดึงจาก $AI_AGENT_SOURCE_URL"
  if ! git clone --depth 1 "$AI_AGENT_SOURCE_URL" "$tmp/src" >/dev/null 2>&1; then
    warn "clone ไม่สำเร็จ — ตรวจ network / สิทธิ์เข้า repo"
    exit 1
  fi
  ok "ได้ $(git -C "$tmp/src" rev-parse --short HEAD)"
  # install.sh ตัวใหม่จะ self-install ทับ $AI_AGENT_HOME แล้วติดตั้งด้วยค่าที่จำไว้
  AI_AGENT_YES=1 "$tmp/src/install.sh"
}

