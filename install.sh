}

# Codex 0.155+ เลิกใช้ ~/.codex/prompts แล้ว — custom command ต้องเป็น skill
# (~/.codex/skills/<name>/SKILL.md) และ frontmatter รับแค่
# name, description, license, allowed-tools, metadata
install_codex() {
  head2 "Codex CLI"
  # AGENTS.md เป็นไฟล์เดี่ยว Codex อ่านผ่าน symlink ได้ปกติ
  link "$SRC/AI.md" "$CODEX_HOME/AGENTS.md"
  ok "$CODEX_HOME/AGENTS.md"

  local file name backed_up=0
  for file in "$SRC"/commands/*.md; do
    name="$(basename "$file" .md)"
    local dest="$CODEX_HOME/skills/$name"
    # skill เดิมที่ไม่ใช่ของเรา → ย้ายไป backup ก่อน ไม่ลบทิ้ง
    if [ -d "$dest" ] && ! grep -q 'generated by ai-agent' "$dest/SKILL.md" 2>/dev/null; then
      mkdir -p "$CODEX_HOME/skills-disabled-old-template"
      mv "$dest" "$CODEX_HOME/skills-disabled-old-template/$name.bak-$STAMP"
      backed_up=$((backed_up + 1))
    fi
    md_to_skill "$file" "$dest/SKILL.md" "$name"
  done
  [ "$backed_up" -gt 0 ] && warn "ย้าย skill เดิม $backed_up ตัวไป $CODEX_HOME/skills-disabled-old-template/"
  ok "$CODEX_HOME/skills/ ($(count "$SRC"/commands/*.md) skills)"

  # prompts ของเก่า (Codex รุ่นเก่า) — เก็บกวาดเฉพาะที่เราสร้างเอง
  for file in "$CODEX_HOME"/prompts/*.md; do
    [ -e "$file" ] || [ -L "$file" ] || continue
    if [ -L "$file" ] || grep -q 'generated by ai-agent' "$file" 2>/dev/null; then
      rm -f "$file"
    fi
  done
  rmdir "$CODEX_HOME/prompts" 2>/dev/null || true

  info "เรียกด้วย \$<name> เช่น \$spec — Codex ใช้ \$ ไม่ใช่ /"
  for file in "$SRC"/agents/*.md; do
    render_agent "$file" codex "$CODEX_HOME/agents/$(basename "$file" .md).toml"
  done
  ok "$CODEX_HOME/agents/ ($(count "$SRC"/agents/*.md) agents)"
}

# Antigravity CLI (agy) ใช้ skill เหมือน Codex — workflows/*.md เป็นของเก่าที่กำลังถูก migrate
# memory: rules เป็น directory-based (GEMINI.md/AGENTS.md ใน repo) ไม่มี global file
#         → skill แต่ละตัวถูก generate ให้อ่าน ~/.ai/AI.md เองตอนเริ่ม
install_antigravity() {
  head2 "Antigravity CLI (agy)"
  local file name backed_up=0 dest
  for file in "$SRC"/commands/*.md; do
    name="$(basename "$file" .md)"
    dest="$AGY_HOME/skills/$name"
    if [ -d "$dest" ] && ! grep -q 'generated by ai-agent' "$dest/SKILL.md" 2>/dev/null; then
      mkdir -p "$AGY_HOME/skills-disabled-old"
      mv "$dest" "$AGY_HOME/skills-disabled-old/$name.bak-$STAMP"
      backed_up=$((backed_up + 1))
    fi
    md_to_skill "$file" "$dest/SKILL.md" "$name"
  done
  [ "$backed_up" -gt 0 ] && warn "ย้าย skill เดิม $backed_up ตัวไป $AGY_HOME/skills-disabled-old/"
  ok "$AGY_HOME/skills/ ($(count "$SRC"/commands/*.md) skills)"
  for file in "$SRC"/agents/*.md; do
    render_agent "$file" antigravity "$AGY_HOME/agents/$(basename "$file")"
  done
  ok "$AGY_HOME/agents/ ($(count "$SRC"/agents/*.md) agents)"
  info "เรียกด้วยชื่อ skill ได้เลย เช่น \"ใช้ skill spec ...\" หรือ /skills ดูรายการ"

  command -v agy >/dev/null 2>&1 || warn "ไม่พบ binary 'agy' ใน PATH — ตรวจว่า ~/.local/bin อยู่ใน PATH หรือยัง"
}

